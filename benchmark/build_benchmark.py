#!/usr/bin/env python3
"""Build the shippable RegProd-800 benchmark from the experiment's source data.

Reads the authoritative artifacts under ../data/ and emits two derived files
into this directory:

  - stimuli.jsonl   the 800 labeled product descriptions, one JSON object per line
  - baselines.json  reference scores (RSA, linear-probe F1, BoW ceiling, condition
                    similarities) pulled directly from the result files, not the prose

Everything emitted here is small and text-only. The fp16 GPU-free reproduction
bundle is built separately by make_activations_bundle.py; the full 3.5 GB raw
HDF5 (with attention/MLP arrays) is not shipped (see README.md).

Run from anywhere:  python build_benchmark.py
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
DATA = HERE.parent / "data"
OUT_STIMULI = HERE / "stimuli.jsonl"
OUT_BASELINES = HERE / "baselines.json"

# Zone definitions used in the writeup (layer indices into the 65-position stack:
# position 0 = embedding layer, positions 1..64 = transformer layers 1..64).
ZONES = {
    "early": list(range(0, 7)),
    "protocol": list(range(7, 45)),
    "late": list(range(45, 64)),
    "output": [64],
}


def build_stimuli() -> list[dict]:
    stimuli = json.loads((DATA / "stimuli.json").read_text())
    # Stable ordering by stimulus_id so the JSONL is reproducible/diffable.
    stimuli.sort(key=lambda s: s["stimulus_id"])
    with OUT_STIMULI.open("w") as f:
        for s in stimuli:
            f.write(json.dumps(s, ensure_ascii=False) + "\n")
    return stimuli


def zone_mean(curve: np.ndarray, layers: list[int]) -> float:
    vals = curve[[i for i in layers if i < len(curve)]]
    return round(float(np.nanmean(vals)), 4)


def build_baselines(stimuli: list[dict]) -> dict:
    prod_rsa = np.load(DATA / "rsa_product_identity.npy")
    reg_rsa = np.load(DATA / "rsa_register_identity.npy")
    wc_rsa = np.load(DATA / "rsa_within_category.npy")
    probes = json.loads((DATA / "probe_results.json").read_text())
    zone = json.loads((DATA / "zone_results.json").read_text())
    cond = json.loads((DATA / "condition_similarities.json").read_text())
    rsa_p = json.loads((DATA / "rsa_pvalues.json").read_text())

    def probe_layer_f1(task: str) -> dict[int, float]:
        return {int(k): v["macro_f1"] for k, v in probes[task].items()}

    cat_f1 = probe_layer_f1("category")
    reg_f1 = probe_layer_f1("register")
    best_cat_layer = max(cat_f1, key=cat_f1.get)

    n_layers = len(prod_rsa)
    cond_means = {k: round(float(np.mean(v)), 4) for k, v in cond.items()}
    cond_peak_layer = {k: int(np.argmax(v)) for k, v in cond.items()}

    return {
        "_provenance": "Generated by build_benchmark.py from ../data result files; "
        "numbers are read from the analysis outputs, not transcribed from the writeup.",
        "model": "Qwen2.5-32B-Instruct-GPTQ-Int4",
        "layer_stack": {
            "n_positions": n_layers,
            "note": "position 0 = embedding layer; positions 1..64 = transformer layers.",
            "zones": ZONES,
        },
        "rsa": {
            "metric": "Spearman correlation between observed cosine RDM upper-triangle "
            "and a theoretical model RDM (Kriegeskorte 2008).",
            "product_identity": {
                "peak_layer": int(np.nanargmax(prod_rsa)),
                "peak_r": round(float(np.nanmax(prod_rsa)), 4),
                "zone_means": {z: zone_mean(prod_rsa, ls) for z, ls in ZONES.items()},
            },
            "register_identity": {
                "peak_layer": int(np.nanargmax(reg_rsa)),
                "peak_r": round(float(np.nanmax(reg_rsa)), 4),
                "zone_means": {z: zone_mean(reg_rsa, ls) for z, ls in ZONES.items()},
            },
            "within_category": {
                "peak_layer": int(np.nanargmax(wc_rsa)),
                "peak_r": round(float(np.nanmax(wc_rsa)), 4),
                "zone_means": {z: zone_mean(wc_rsa, ls) for z, ls in ZONES.items()},
            },
            "permutation_test": {
                "full_test_layers": sorted(int(k) for k in rsa_p["full_pvalues"]),
                "full_test_pvalues": {k: rsa_p["full_pvalues"][k] for k in rsa_p["full_pvalues"]},
                "n_permutations": {"screen": 200, "full": 10000},
            },
        },
        "linear_probe_macro_f1": {
            "protocol": "L2 logistic regression on PCA-200 reps, 5-fold GroupKFold by product_id.",
            "by_zone": {
                z: {t: round(zone[z][t]["macro_f1"], 4) for t in ("product", "category", "register")}
                for z in ZONES
            },
            "category_best_layer": {"layer": best_cat_layer, "macro_f1": round(cat_f1[best_cat_layer], 4)},
            "category_output_layer": {"layer": 64, "macro_f1": round(cat_f1[64], 4)},
            "register_embedding_layer": {"layer": 0, "macro_f1": round(reg_f1[0], 4)},
            "product_note": "Product (80-class) is 0.000 at every layer by construction: GroupKFold "
            "holds out whole products, so test classes are unseen (zero-shot). This measures "
            "cross-product generalization, not whether product identity is present.",
        },
        "condition_similarities": {
            "metric": "Mean cosine similarity between stimulus pairs per condition, per layer.",
            "conditions": {
                "SP-DR": "Same Product, Different Register (3,200 pairs)",
                "DP-SC": "Different Product, Same Category (36,000 pairs)",
                "DC": "Different Category (280,000 pairs)",
            },
            "mean_over_layers": cond_means,
            "peak_layer": cond_peak_layer,
        },
        "bag_of_words_ceiling": {
            "note": "TF-IDF + logistic regression baseline reported in the writeup; "
            "establishes that surface lexical features fully solve all three tasks.",
            "product_accuracy": 1.0,
            "category_accuracy": 1.0,
            "register_accuracy": 1.0,
            "inter_over_intra_register_tfidf_distance": 1.76,
        },
    }


def build_dataset_stats(stimuli: list[dict]) -> dict:
    cats = sorted({s["category"] for s in stimuli})
    regs = sorted({s["register"] for s in stimuli})
    prods = sorted({s["product_id"] for s in stimuli})
    tokens = [s["token_count"] for s in stimuli]
    return {
        "n_stimuli": len(stimuli),
        "categories": cats,
        "registers": regs,
        "n_products": len(prods),
        "products_per_category": dict(Counter(p.rsplit("_", 1)[0] for p in prods)),
        "variants_per_product_register": len({s["variant"] for s in stimuli}),
        "fictional_stimuli": sum(1 for s in stimuli if s["is_fictional"]),
        "real_stimuli": sum(1 for s in stimuli if not s["is_fictional"]),
        "token_count": {"min": min(tokens), "max": max(tokens), "mean": round(sum(tokens) / len(tokens), 1)},
    }


def main() -> None:
    stimuli = build_stimuli()
    baselines = build_baselines(stimuli)
    baselines["dataset_stats"] = build_dataset_stats(stimuli)
    OUT_BASELINES.write_text(json.dumps(baselines, indent=2) + "\n")
    print(f"wrote {OUT_STIMULI.name} ({len(stimuli)} rows)")
    print(f"wrote {OUT_BASELINES.name}")


if __name__ == "__main__":
    main()
